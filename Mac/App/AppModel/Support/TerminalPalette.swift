import SwiftTerm

enum TerminalPalette {
    static func colors(isDark: Bool) -> [SwiftTerm.Color] {
        isDark ? dark : light
    }

    private static func color(_ red: UInt16, _ green: UInt16, _ blue: UInt16) -> SwiftTerm.Color {
        SwiftTerm.Color(red: red * 257, green: green * 257, blue: blue * 257)
    }

    private static let dark: [SwiftTerm.Color] = [
        color(0x00, 0x00, 0x00), color(0xcd, 0x31, 0x31), color(0x0d, 0xbc, 0x79), color(0xe5, 0xe5, 0x10),
        color(0x24, 0x72, 0xc8), color(0xbc, 0x3f, 0xbc), color(0x11, 0xa8, 0xcd), color(0xe5, 0xe5, 0xe5),
        color(0x66, 0x66, 0x66), color(0xf1, 0x4c, 0x4c), color(0x23, 0xd1, 0x8b), color(0xf5, 0xf5, 0x43),
        color(0x3b, 0x8e, 0xea), color(0xd6, 0x70, 0xd6), color(0x29, 0xb8, 0xdb), color(0xe5, 0xe5, 0xe5),
    ]

    private static let light: [SwiftTerm.Color] = [
        color(0x00, 0x00, 0x00), color(0xcd, 0x31, 0x31), color(0x00, 0xbc, 0x00), color(0x94, 0x95, 0x00),
        color(0x00, 0x06, 0xc8), color(0xbc, 0x05, 0xbc), color(0x00, 0x98, 0xa8), color(0x55, 0x55, 0x55),
        color(0x66, 0x66, 0x66), color(0xcd, 0x31, 0x31), color(0x14, 0xce, 0x14), color(0xb5, 0xba, 0x00),
        color(0x04, 0x51, 0xa5), color(0xbc, 0x05, 0xbc), color(0x00, 0x98, 0xa8), color(0xa5, 0xa5, 0xa5),
    ]
}
